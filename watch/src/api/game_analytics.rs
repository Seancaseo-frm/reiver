/// Validate that a session_id is a valid format.
///
/// Session IDs should be UUIDs (generated by the SDK as Guid.NewGuid().ToString()).
/// This validates the format to prevent malformed or malicious input.
fn validate_session_id(session_id: &str) -> Result<&str> {
    // Session IDs should be valid UUIDs
    uuid::Uuid::parse_str(session_id).map_err(|_| {
        AppError::Validation(format!(
            "Invalid session_id format: '{}'. Expected a valid UUID.",
            if session_id.len() > 50 {
                &session_id[..50]
            } else {
                session_id
            }
        ))
    })?;
    Ok(session_id)
}

/// Validate that a match_id is a valid format.
///
/// Match IDs should be UUIDs or alphanumeric identifiers.
/// This validates the format to prevent malformed or malicious input.
fn validate_match_id(match_id: &str) -> Result<&str> {
    // Try UUID format first (most common)
    if uuid::Uuid::parse_str(match_id).is_ok() {
        return Ok(match_id);
    }

    // Allow alphanumeric IDs with hyphens/underscores (max 64 chars)
    if match_id.len() <= 64
        && match_id
            .chars()
            .all(|c| c.is_alphanumeric() || c == '-' || c == '_')
    {
        return Ok(match_id);
    }

    Err(AppError::Validation(format!(
        "Invalid match_id format: '{}'. Expected a UUID or alphanumeric identifier.",
        if match_id.len() > 50 {
            &match_id[..50]
        } else {
            match_id
        }
    )))
}

