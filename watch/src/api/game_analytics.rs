async fn list_player_sessions(
    State(state): State<Arc<WatchState>>,
    headers: HeaderMap,
    Query(query): Query<SessionListQuery>,
) -> Result<Json<Vec<PlayerSession>>> {
    let project_id = crate::api::extract_project_id(&headers)?;

    // Use validated and sanitized parameters
    let limit = query.validated_limit();
    let offset = query.validated_offset();

    let mut conditions = vec!["project_id = ?".to_string()];

    if query.player_id.is_some() {
        conditions.push("player_id = ?".to_string());
    }

    if query.platform.is_some() {
        conditions.push("platform = ?".to_string());
    }

    if query.validated_min_quality_score().is_some() {
        conditions.push("quality_score >= ?".to_string());
    }

    if query.end_reason.is_some() {
        conditions.push("end_reason = ?".to_string());
    }

    let sql = format!(
        r#"
        SELECT
            session_id,
            player_id,
            platform,
            device_model,
            gpu_model,
            game_version,
            start_time,
            end_time,
            duration_seconds,
            end_reason,
            avg_fps,
            min_fps,
            p95_frame_time_seconds,
            avg_rtt_seconds,
            avg_jitter_seconds,
            packet_loss_ratio,
            peak_memory_bytes,
            matches_played,
            matches_completed,
            quality_score,
            country_code,
            region
        FROM reiver.game_player_sessions
        WHERE {}
        ORDER BY start_time DESC
        LIMIT ? OFFSET ?
        "#,
        conditions.join(" AND ")
    );

    // Build query with bound parameters
    let mut query_builder = state.clickhouse.as_ref().query(&sql);
    query_builder = query_builder.bind(project_id.to_string());

    if let Some(ref player_id) = query.player_id {
        query_builder = query_builder.bind(player_id.clone());
    }

    if let Some(ref platform) = query.platform {
        query_builder = query_builder.bind(platform.clone());
    }

    if let Some(min_score) = query.validated_min_quality_score() {
        query_builder = query_builder.bind(min_score);
    }

    if let Some(ref end_reason) = query.end_reason {
        query_builder = query_builder.bind(end_reason.clone());
    }

    query_builder = query_builder.bind(limit as u64).bind(offset as u64);

    // Execute query
    let rows: Vec<PlayerSessionRow> = query_builder
        .fetch_all()
        .await
        .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

    // Convert to API response type
    let sessions: Vec<PlayerSession> = rows
        .into_iter()
        .map(|row| PlayerSession {
            session_id: row.session_id,
            player_id: row.player_id,
            platform: row.platform,
            device_model: row.device_model,
            gpu_model: row.gpu_model,
            game_version: row.game_version,
            start_time: row.start_time,
            end_time: row.end_time,
            duration_seconds: row.duration_seconds,
            end_reason: row.end_reason,
            avg_fps: row.avg_fps,
            min_fps: row.min_fps,
            p95_frame_time_seconds: row.p95_frame_time_seconds,
            avg_rtt_seconds: row.avg_rtt_seconds,
            avg_jitter_seconds: row.avg_jitter_seconds,
            packet_loss_ratio: row.packet_loss_ratio,
            peak_memory_bytes: row.peak_memory_bytes,
            matches_played: row.matches_played,
            matches_completed: row.matches_completed,
            quality_score: row.quality_score,
            country_code: row.country_code,
            region: row.region,
        })
        .collect();

    Ok(Json(sessions))
}

