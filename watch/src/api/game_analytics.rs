async fn get_geographic_latency(
    State(state): State<Arc<WatchState>>,
    headers: HeaderMap,
    Query(query): Query<GeoLatencyQuery>,
) -> Result<Json<GeoLatencyData>> {
    let project_id = crate::api::extract_project_id(&headers)?;

    let time_range = validate_time_range(query.time_range.as_deref().unwrap_or("24h"));
    let interval = time_range_to_interval(time_range);

    // Query country-level latency stats
    let country_sql = format!(
        r#"
        SELECT
            country_code,
            count() as player_count,
            avg(avg_rtt_seconds) * 1000 as avg_rtt_ms,
            quantile(0.95)(avg_rtt_seconds) * 1000 as p95_rtt_ms,
            avg(packet_loss_ratio) as avg_packet_loss
        FROM reiver.game_player_sessions
        WHERE project_id = ? AND start_time >= now() - INTERVAL {}
        GROUP BY country_code
        ORDER BY player_count DESC
        LIMIT 50
        "#,
        interval
    );

    let country_rows: Vec<CountryLatencyRow> = state
        .clickhouse
        .as_ref()
        .query(&country_sql)
        .bind(project_id.to_string())
        .fetch_all()
        .await
        .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

    // Query region-level latency stats
    let mut region_sql = format!(
        r#"
        SELECT
            region,
            server_region,
            count() as player_count,
            avg(avg_rtt_seconds) * 1000 as avg_rtt_ms,
            min(avg_rtt_seconds) * 1000 as min_rtt_ms,
            max(avg_rtt_seconds) * 1000 as max_rtt_ms
        FROM reiver.game_player_sessions ps
        JOIN reiver.game_match_players mp ON ps.session_id = mp.session_id
        JOIN reiver.game_matches m ON mp.match_id = m.match_id
        WHERE ps.project_id = ? AND ps.start_time >= now() - INTERVAL {}
        "#,
        interval
    );

    if let Some(ref server_region) = query.server_region {
        region_sql.push_str(" AND m.server_region = ?");
        region_sql.push_str(" GROUP BY region, server_region ORDER BY player_count DESC LIMIT 50");

        let region_rows: Vec<RegionLatencyRow> = state
            .clickhouse
            .as_ref()
            .query(&region_sql)
            .bind(project_id.to_string())
            .bind(server_region.clone())
            .fetch_all()
            .await
            .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

        let regions: Vec<RegionLatency> = region_rows
            .into_iter()
            .map(|row| RegionLatency {
                region: row.region,
                server_region: row.server_region,
                player_count: row.player_count,
                avg_rtt_ms: row.avg_rtt_ms,
                min_rtt_ms: row.min_rtt_ms,
                max_rtt_ms: row.max_rtt_ms,
            })
            .collect();

        let countries: Vec<CountryLatency> = country_rows
            .into_iter()
            .map(|row| CountryLatency {
                country_name: get_country_name(&row.country_code),
                country_code: row.country_code,
                player_count: row.player_count,
                avg_rtt_ms: row.avg_rtt_ms,
                p95_rtt_ms: row.p95_rtt_ms,
                avg_packet_loss: row.avg_packet_loss,
            })
            .collect();

        return Ok(Json(GeoLatencyData { countries, regions }));
    }

    region_sql.push_str(" GROUP BY region, server_region ORDER BY player_count DESC LIMIT 50");

    let region_rows: Vec<RegionLatencyRow> = state
        .clickhouse
        .as_ref()
        .query(&region_sql)
        .bind(project_id.to_string())
        .fetch_all()
        .await
        .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

    let countries: Vec<CountryLatency> = country_rows
        .into_iter()
        .map(|row| CountryLatency {
            country_name: get_country_name(&row.country_code),
            country_code: row.country_code,
            player_count: row.player_count,
            avg_rtt_ms: row.avg_rtt_ms,
            p95_rtt_ms: row.p95_rtt_ms,
            avg_packet_loss: row.avg_packet_loss,
        })
        .collect();

    let regions: Vec<RegionLatency> = region_rows
        .into_iter()
        .map(|row| RegionLatency {
            region: row.region,
            server_region: row.server_region,
            player_count: row.player_count,
            avg_rtt_ms: row.avg_rtt_ms,
            min_rtt_ms: row.min_rtt_ms,
            max_rtt_ms: row.max_rtt_ms,
        })
        .collect();

    Ok(Json(GeoLatencyData { countries, regions }))
}

async fn get_latency_heatmap(
    State(state): State<Arc<WatchState>>,
    headers: HeaderMap,
    Query(query): Query<GeoLatencyQuery>,
) -> Result<Json<LatencyHeatmap>> {
    let project_id = crate::api::extract_project_id(&headers)?;
    let time_range = validate_time_range(query.time_range.as_deref().unwrap_or("24h"));
    let interval = time_range_to_interval(time_range);

    // Build client_region x server_region heatmap
    let sql = format!(
        r#"
        SELECT
            ps.region as client_region,
            m.server_region,
            avg(ps.avg_rtt_seconds) * 1000 as avg_rtt_ms,
            count() as player_count
        FROM reiver.game_player_sessions ps
        JOIN reiver.game_match_players mp ON ps.session_id = mp.session_id
        JOIN reiver.game_matches m ON mp.match_id = m.match_id
        WHERE ps.project_id = ? AND ps.start_time >= now() - INTERVAL {}
        GROUP BY ps.region, m.server_region
        HAVING player_count >= 10
        ORDER BY player_count DESC
        LIMIT 200
        "#,
        interval
    );

    let rows: Vec<HeatmapCellRow> = state
        .clickhouse
        .as_ref()
        .query(&sql)
        .bind(project_id.to_string())
        .fetch_all()
        .await
        .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

    let cells: Vec<HeatmapCell> = rows
        .iter()
        .map(|row| HeatmapCell {
            client_region: row.client_region.clone(),
            server_region: row.server_region.clone(),
            avg_rtt_ms: row.avg_rtt_ms,
            player_count: row.player_count,
        })
        .collect();

    let min_latency_ms = rows.iter().map(|r| r.avg_rtt_ms).fold(f64::MAX, f64::min);
    let max_latency_ms = rows.iter().map(|r| r.avg_rtt_ms).fold(0.0_f64, f64::max);

    Ok(Json(LatencyHeatmap {
        cells,
        min_latency_ms: if min_latency_ms == f64::MAX {
            0.0
        } else {
            min_latency_ms
        },
        max_latency_ms,
    }))
}

