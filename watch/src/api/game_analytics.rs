/// ClickHouse row type for session quality metrics
#[derive(clickhouse::Row, Deserialize)]
struct SessionMetricsRow {
    avg_fps: f64,
    min_fps: f64,
    p95_frame_time_seconds: f64,
    avg_rtt_seconds: f64,
    avg_jitter_seconds: f64,
    packet_loss_ratio: f64,
}

/// Calculate a composite quality score for a player session.
///
/// The score is computed from multiple factors:
/// - FPS Score (30%): Based on average FPS and minimum FPS
/// - Latency Score (25%): Based on RTT and jitter
/// - Stability Score (25%): Based on frame time consistency and crashes
/// - Network Score (20%): Based on packet loss
///
/// Each factor is normalized to 0-100, then weighted to produce the final score.
async fn calculate_session_quality(
    state: &Arc<WatchState>,
    project_id: &str,
    session_id: &str,
) -> Result<SessionQuality> {
    // Fetch session metrics from ClickHouse
    let sql = r#"
        SELECT
            avg_fps,
            min_fps,
            p95_frame_time_seconds,
            avg_rtt_seconds,
            avg_jitter_seconds,
            packet_loss_ratio
        FROM reiver.game_player_sessions
        WHERE project_id = ? AND session_id = ?
        LIMIT 1
    "#;

    let rows: Vec<SessionMetricsRow> = state
        .clickhouse
        .as_ref()
        .query(sql)
        .bind(project_id)
        .bind(session_id)
        .fetch_all()
        .await
        .map_err(|e| AppError::Internal(anyhow!("ClickHouse query failed: {}", e)))?;

    let metrics = rows
        .into_iter()
        .next()
        .ok_or_else(|| AppError::NotFound(format!("Session {} not found", session_id)))?;

    let avg_fps = metrics.avg_fps;
    let min_fps = metrics.min_fps;
    let p95_frame_time = metrics.p95_frame_time_seconds;
    let avg_rtt = metrics.avg_rtt_seconds;
    let jitter = metrics.avg_jitter_seconds;
    let packet_loss = metrics.packet_loss_ratio;
    // Crash count is inferred from end_reason in a more complete implementation
    let crash_count: u32 = 0;

    // FPS Score (0-100)
    // 60+ FPS = 100, 30 FPS = 50, <15 FPS = 0
    let fps_score = calculate_fps_score(avg_fps, min_fps);

    // Latency Score (0-100)
    // <30ms = 100, 100ms = 50, >200ms = 0
    let latency_score = calculate_latency_score(avg_rtt, jitter);

    // Stability Score (0-100)
    // Based on frame time consistency and crash-free
    let stability_score = calculate_stability_score(p95_frame_time, avg_fps, crash_count);

    // Network Score (0-100)
    // 0% loss = 100, 2% loss = 50, >5% loss = 0
    let network_score = calculate_network_score(packet_loss);

    // Weighted average
    let overall_score =
        fps_score * 0.30 + latency_score * 0.25 + stability_score * 0.25 + network_score * 0.20;

    let factors = vec![
        QualityFactor {
            name: "FPS".to_string(),
            weight: 0.30,
            score: fps_score,
            value: avg_fps,
            threshold_good: 60.0,
            threshold_poor: 30.0,
        },
        QualityFactor {
            name: "Latency".to_string(),
            weight: 0.25,
            score: latency_score,
            value: avg_rtt * 1000.0, // Convert to ms for display
            threshold_good: 30.0,
            threshold_poor: 100.0,
        },
        QualityFactor {
            name: "Stability".to_string(),
            weight: 0.25,
            score: stability_score,
            value: p95_frame_time * 1000.0, // Convert to ms
            threshold_good: 16.67,          // 60fps target
            threshold_poor: 33.33,          // 30fps minimum
        },
        QualityFactor {
            name: "Network".to_string(),
            weight: 0.20,
            score: network_score,
            value: packet_loss * 100.0, // Convert to percentage
            threshold_good: 0.5,
            threshold_poor: 2.0,
        },
    ];

    Ok(SessionQuality {
        session_id: session_id.to_string(),
        overall_score,
        fps_score,
        latency_score,
        stability_score,
        network_score,
        factors,
    })
}

fn calculate_fps_score(avg_fps: f64, min_fps: f64) -> f64 {
    // Score based on average FPS (70%) and minimum FPS (30%)
    let avg_score = if avg_fps >= 60.0 {
        100.0
    } else if avg_fps >= 30.0 {
        50.0 + (avg_fps - 30.0) / 30.0 * 50.0
    } else if avg_fps >= 15.0 {
        (avg_fps - 15.0) / 15.0 * 50.0
    } else {
        0.0
    };

    let min_score = if min_fps >= 30.0 {
        100.0
    } else if min_fps >= 15.0 {
        50.0 + (min_fps - 15.0) / 15.0 * 50.0
    } else {
        (min_fps / 15.0) * 50.0
    };

    avg_score * 0.7 + min_score * 0.3
}

fn calculate_latency_score(avg_rtt_seconds: f64, jitter_seconds: f64) -> f64 {
    let rtt_ms = avg_rtt_seconds * 1000.0;
    let jitter_ms = jitter_seconds * 1000.0;

    // RTT score (80%)
    let rtt_score = if rtt_ms <= 30.0 {
        100.0
    } else if rtt_ms <= 100.0 {
        100.0 - (rtt_ms - 30.0) / 70.0 * 50.0
    } else if rtt_ms <= 200.0 {
        50.0 - (rtt_ms - 100.0) / 100.0 * 50.0
    } else {
        0.0
    };

    // Jitter score (20%)
    let jitter_score = if jitter_ms <= 5.0 {
        100.0
    } else if jitter_ms <= 20.0 {
        100.0 - (jitter_ms - 5.0) / 15.0 * 50.0
    } else if jitter_ms <= 50.0 {
        50.0 - (jitter_ms - 20.0) / 30.0 * 50.0
    } else {
        0.0
    };

    rtt_score * 0.8 + jitter_score * 0.2
}

fn calculate_stability_score(p95_frame_time_seconds: f64, avg_fps: f64, crash_count: u32) -> f64 {
    // Crash penalty
    if crash_count > 0 {
        return 0.0;
    }

    let p95_frame_time_ms = p95_frame_time_seconds * 1000.0;
    let target_frame_time_ms = 1000.0 / avg_fps.max(1.0);

    // How much variance from target frame time
    let variance_ratio = p95_frame_time_ms / target_frame_time_ms;

    if variance_ratio <= 1.2 {
        100.0
    } else if variance_ratio <= 1.5 {
        100.0 - (variance_ratio - 1.2) / 0.3 * 30.0
    } else if variance_ratio <= 2.0 {
        70.0 - (variance_ratio - 1.5) / 0.5 * 40.0
    } else {
        (30.0 / variance_ratio).max(0.0)
    }
}

fn calculate_network_score(packet_loss_ratio: f64) -> f64 {
    let loss_percent = packet_loss_ratio * 100.0;

    if loss_percent <= 0.5 {
        100.0
    } else if loss_percent <= 2.0 {
        100.0 - (loss_percent - 0.5) / 1.5 * 50.0
    } else if loss_percent <= 5.0 {
        50.0 - (loss_percent - 2.0) / 3.0 * 50.0
    } else {
        0.0
    }
}

